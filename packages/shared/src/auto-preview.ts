import { behaviourFor, contentBehaviourFor, type Control, type InterfaceSpec } from "./spec.js";
// The vocabulary the preview frame reads too, so both origins answer "is this
// spatial / a duration / an easing picker" the same way. See vocab.js.
import { isEasingSelect } from "./vocab.js";
import { planPreview } from "./preview-plan.js";

export { isEasingSelect };

/**
 * Whether a spec has anything worth showing without the agent writing a preview.
 *
 * The rule, arrived at from real use: anything with a MAGNITUDE deserves a
 * visual — a colour, a length, a duration, a type size. You cannot judge "760px"
 * or "#b0367a" from a number. Toggles, selects and free text are
 * self-describing, and forcing them into a picture would add chrome that says
 * nothing.
 *
 * Getting this wrong in the generous direction is the safer failure: a slightly
 * redundant preview costs a little space, whereas a missing one means the human
 * is guessing while the UI looks authoritative.
 */

/**
 * Does anything on screen change when this control moves? Used only for
 * ORDERING controls, which is a weaker question than "can the preview draw it"
 * — a control can be illustrated by an agent's own preview module, by a
 * `sample` block, by a bound snippet, or by its own renderer, without the
 * built-in helper knowing how to draw a thing.
 *
 * Keeping this separate from the PLAN is what stops "referenced by an effect ⇒
 * visual" from also opening a preview FRAME: a widget whose only illustrated
 * control is a compare would otherwise ship half a screen of pane containing
 * the string "Retries: 3".
 *
 * There is deliberately no `isPreviewSubject` beside it any more. That was a
 * second answer to "would the preview draw this", and a second answer is how a
 * "type_scale" control ended up in the frame's font bucket while the gate said
 * there was nothing to show. `planPreview` is the only answer now.
 */
export function controlIsIllustrated(spec: InterfaceSpec, control: Control): boolean {
  // The per-control half of the answer belongs to the control; the per-block
  // half belongs to the block. Both used to be if-chains here that every new
  // type and kind had to be remembered in.
  if (behaviourFor(control).illustrated?.(control)) return true;

  return spec.content.some((block) => {
    const illustrates = contentBehaviourFor(block).illustrates?.(block);
    return illustrates?.includes(control.id) ?? false;
  });
}

export function shouldAutoPreview(spec: InterfaceSpec): boolean {
  // An agent can decline a generated preview outright. Without this the only
  // way to suppress one was to delete `unit`, which the skill rightly forbids.
  if (spec.preview?.auto === false) return false;
  // Asks the PLAN, rather than answering separately and hoping the two agree.
  // They did not, once: a "type_scale" control landed in the frame's font
  // bucket while this said there was nothing to show, so the frame never
  // opened. Same function now, so that is no longer a thing that can happen.
  return planPreview(spec).drawsSomething;
}

/**
 * The module served for a spec with no authored preview. Deliberately tiny: all
 * the work lives in the shared helper, so improving previews improves every
 * widget that never asked for one.
 */
export const AUTO_PREVIEW_MODULE = `import { autoPreview } from "agentui";

// Generated by AgentUI because this widget has values with a visible magnitude
// and no previewModule of its own. Supply one to ui_create to replace it.
let impl = null;
export default {
  setup(ctx) {
    impl = autoPreview(ctx.spec);
    return impl.setup(ctx);
  },
  update(values, meta) {
    impl?.update(values, meta);
  },
};
`;
